import request from "supertest";
import { beforeEach, describe, expect, it } from "vitest";
import { EXPECTED } from "./alertExpectations.js";
import { loadFixtureRaw } from "./alertFixtures.js";
import { coverReply, prepReply, resumeReply } from "./documentFakes.js";
import { VALID_FORM } from "./helpers.js";
import { buildApp, signUp } from "./jobsApp.js";
import { createScriptedProvider, llmReply } from "./matchFakes.js";

const recent = (n) => new Date(Date.now() - n * 86400000);
const mailbox = () => [
  { id: "m1", from: `Indeed <${EXPECTED.indeed.sender}>`, receivedAt: recent(3), raw: loadFixtureRaw("indeed.eml") },
  { id: "m2", from: EXPECTED.naukri.sender, receivedAt: recent(2), raw: loadFixtureRaw("naukri_1.eml") },
  { id: "m3", from: EXPECTED.shine.sender, receivedAt: recent(1), raw: loadFixtureRaw("shine_1.eml") },
];

/** Answers each kind of prompt with a valid reply for it, so one provider serves scoring and all three documents. */
const kindOf = (prompt) =>
  /scoring how well/.test(prompt) ? "score"
    : /tailor a candidate/.test(prompt) ? "resume"
      : /short cover note/.test(prompt) ? "cover_note"
        : /prepare a candidate/.test(prompt) ? "prep_kit"
          : "unknown";
const REPLIES = { score: () => llmReply({ score: 88 }), resume: () => resumeReply(), cover_note: () => coverReply(150), prep_kit: () => prepReply() };
const respond = (prompt) => REPLIES[kindOf(prompt)]();

async function appWithFixtureJobs({ provider = createScriptedProvider([], { respond }) } = {}) {
  const ctx = await buildApp({ provider, mailbox: mailbox() });
  const { agent, userId } = await signUp(ctx.app);
  const state = new URL((await agent.get("/api/gmail/connect")).headers.location).searchParams.get("state");
  await agent.get("/api/gmail/callback").query({ code: "ok", state }).expect(302);
  await agent.post("/api/gmail/sync").expect(200);
  await Promise.all(ctx.scoring.runs);
  return { ...ctx, agent, userId, provider };
}

const jobTitled = (ctx, title) => ctx.jobRepository.jobs.find((j) => j.title === title);

describe("documents for a fixture job", () => {
  let ctx;
  let job;
  beforeEach(async () => {
    ctx = await appWithFixtureJobs();
    job = jobTitled(ctx, "Backend Developer - Node.js, Heroku, PostgreSQL"); // from naukri_1.eml
  });

  it("starts with no documents, and nothing was generated by the sync, scoring or resume update", async () => {
    expect(job).toBeTruthy();
    const res = await ctx.agent.get(`/api/jobs/${job.id}/documents`);
    expect(res.status).toBe(200);
    expect(res.body).toEqual({ documents: { resume: null, cover_note: null, prep_kit: null } });

    // Sync scored 34 jobs, then a resume update rescored them. No document prompt was ever sent.
    await ctx.agent.post("/api/resumes/create").send({ ...VALID_FORM, skills: ["Node.js"] }).expect(201);
    await ctx.agent.post(`/api/jobs/${job.id}/rescore`).expect(200);
    const kinds = new Set(ctx.provider.prompts.map(kindOf));
    expect(kinds).toEqual(new Set(["score"]));
    expect(ctx.documentRepository.docs).toHaveLength(0);
  });

  it("generates all three document types on request", async () => {
    for (const type of ["resume", "cover_note", "prep_kit"]) {
      const res = await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type });
      expect(res.status, type).toBe(201);
      expect(res.body.document).toMatchObject({
        type, jobId: job.id, version: 1, modelUsed: "scripted-model", limitedInfo: expect.any(Boolean),
        content: { text: expect.any(String) },
      });
    }

    const { documents } = (await ctx.agent.get(`/api/jobs/${job.id}/documents`)).body;
    expect(documents.resume.content.structured.skills).toEqual(["PostgreSQL", "Node.js", "React"]);
    expect(documents.resume.content.text).toContain("Asha Rai");
    expect(documents.cover_note.content.wordCount).toBe(150);
    expect(documents.prep_kit.content.likelyQuestions).toHaveLength(10);
    expect(documents.prep_kit.content.questionsToAsk).toHaveLength(5);
    expect(documents.prep_kit.content.technicalTopics.every((t) => t.youtubeQueries.length > 0)).toBe(true);
    expect(JSON.stringify(documents.prep_kit)).not.toMatch(/https?:|youtube\.com|youtu\.be/);
  });

  it("generation only happens when asked: one POST sends one document prompt", async () => {
    const before = ctx.provider.prompts.length;
    await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type: "cover_note" }).expect(201);
    expect(ctx.provider.prompts.slice(before).map(kindOf)).toEqual(["cover_note"]);
  });

  it("regenerating creates version 2, GET returns the latest, older versions stay in storage", async () => {
    const v1 = (await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type: "cover_note" })).body.document;
    const v2 = (await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type: "cover_note" })).body.document;
    expect([v1.version, v2.version]).toEqual([1, 2]);
    const latest = (await ctx.agent.get(`/api/jobs/${job.id}/documents`)).body.documents.cover_note;
    expect(latest.id).toBe(v2.id);
    expect(ctx.documentRepository.docs.filter((d) => d.type === "cover_note").map((d) => d.version)).toEqual([1, 2]);
  });

  it("the job detail endpoint returns the job, its match, the snippet and the limited-info flag", async () => {
    const res = await ctx.agent.get(`/api/jobs/${job.id}`);
    expect(res.status).toBe(200);
    expect(res.body.job).toMatchObject({
      id: job.id, title: job.title, company: "Bahwan CyberTek", sourcePortal: "naukri", needsLink: false,
      jobUrl: expect.stringContaining("https://www.naukri.com/jd/job-listings-"),
      snippet: job.raw_snippet, limitedInfo: job.raw_snippet.trim().length < 100,
      match: { score: 88, label: "Strong match: review skill gaps", llmFailed: false },
    });
    expect(JSON.stringify(res.body)).not.toContain("raw_snippet");
  });

  it("limited_info follows each fixture job's real snippet length, for every job in all three emails", async () => {
    const jobs = ctx.jobRepository.jobs;
    expect(jobs).toHaveLength(34);
    const flags = [];
    for (const j of jobs) {
      const res = await ctx.agent.post(`/api/jobs/${j.id}/documents`).send({ type: "cover_note" });
      expect(res.status).toBe(201);
      const expected = j.raw_snippet.trim().length < 100;
      expect(res.body.document.limitedInfo, `${j.source_portal}: ${j.title}`).toBe(expected);
      expect(res.body.document.limitedInfoNote).toBe(expected ? "Based on limited job details. Open the posting for the full description." : null);
      flags.push(expected);
    }
    // The fixtures contain both kinds, so this test really exercises both branches.
    expect(flags).toContain(true);
    expect(flags).toContain(false);
  });
});

describe("document errors", () => {
  it("an invalid tailored resume is an error response, with no document stored and no leaked output", async () => {
    const provider = createScriptedProvider([], {
      respond: (p) => (kindOf(p) === "resume" ? resumeReply({ skills: ["Node.js", "Kafka"], experience: [{ role: "Engineer", company: "Globex", dates: "2021 - 2024", bullets: [] }] }) : respond(p)),
    });
    const ctx = await appWithFixtureJobs({ provider });
    const job = jobTitled(ctx, "Backend Developer - Node.js, Heroku, PostgreSQL");
    const before = provider.prompts.length;

    const res = await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type: "resume" });

    expect(res.status).toBe(422);
    expect(res.body).toEqual({ error: { code: "DOCUMENT_VALIDATION_FAILED", message: expect.any(String) } });
    expect(JSON.stringify(res.body)).not.toMatch(/Kafka|Globex/);
    expect(provider.prompts.length - before).toBe(2); // first attempt + exactly one regeneration
    expect(ctx.documentRepository.docs).toHaveLength(0);
    expect((await ctx.agent.get(`/api/jobs/${job.id}/documents`)).body.documents.resume).toBeNull();
  });

  it("is a 503 when no AI key is configured, and reading still works", async () => {
    const ctx = await appWithFixtureJobs({ provider: null });
    const job = ctx.jobRepository.jobs[0];
    const res = await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type: "cover_note" });
    expect(res.status).toBe(503);
    expect(res.body.error.code).toBe("AI_NOT_CONFIGURED");
    expect((await ctx.agent.get(`/api/jobs/${job.id}/documents`)).status).toBe(200);
  });

  it("validates the request", async () => {
    const ctx = await appWithFixtureJobs();
    const id = ctx.jobRepository.jobs[0].id;
    for (const body of [{}, { type: "poem" }, { type: "resume", extra: 1 }, { type: ["resume"] }, { type: null }]) {
      const res = await ctx.agent.post(`/api/jobs/${id}/documents`).send(body);
      expect(res.status, JSON.stringify(body)).toBe(400);
      expect(res.body.error.code).toBe("VALIDATION_ERROR");
    }
    expect((await ctx.agent.post("/api/jobs/not-a-uuid/documents").send({ type: "resume" })).status).toBe(400);
    expect((await ctx.agent.get("/api/jobs/not-a-uuid/documents")).status).toBe(400);
    expect((await ctx.agent.get("/api/jobs/not-a-uuid")).status).toBe(400);
  });

  it("requires login and a resume", async () => {
    const ctx = await appWithFixtureJobs();
    const id = ctx.jobRepository.jobs[0].id;
    for (const [method, path] of [["get", `/api/jobs/${id}`], ["get", `/api/jobs/${id}/documents`], ["post", `/api/jobs/${id}/documents`]]) {
      expect((await request(ctx.app)[method](path).send({ type: "resume" })).status, path).toBe(401);
    }
    const { agent: noResume } = await signUp(ctx.app, "n@example.com", { resume: false });
    const res = await noResume.post(`/api/jobs/${id}/documents`).send({ type: "resume" });
    expect(res.status).toBe(403);
    expect(res.body.error.code).toBe("RESUME_REQUIRED");
  });

  it("another user can't read, generate or see a job that isn't theirs", async () => {
    const ctx = await appWithFixtureJobs();
    const job = ctx.jobRepository.jobs[0];
    await ctx.agent.post(`/api/jobs/${job.id}/documents`).send({ type: "cover_note" }).expect(201);

    const { agent: other } = await signUp(ctx.app, "other@example.com");
    expect((await other.get(`/api/jobs/${job.id}`)).status).toBe(404);
    expect((await other.get(`/api/jobs/${job.id}/documents`)).status).toBe(404);
    expect((await other.post(`/api/jobs/${job.id}/documents`).send({ type: "cover_note" })).status).toBe(404);
    expect(ctx.documentRepository.docs).toHaveLength(1);
  });
});
